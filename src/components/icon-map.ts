/// Every icon the app uses, named for what it means rather than what it looks like.
///
/// This replaces emoji. Emoji render differently on every platform — Apple, Google and Microsoft
/// each draw their own, so a screen designed against one set is a different screen on another —
/// they sit on the text baseline rather than aligning with it, they cannot be recoloured to match
/// a theme, and screen readers announce their full Unicode name ("rocket", "high voltage") in the
/// middle of a sentence that was not written to contain it.
///
/// Naming by meaning is what keeps that from happening again. A page asks for `deadline`, not for
/// a calendar glyph, so the drawing can change in one place without hunting through 29 files — and
/// the full vocabulary of the product is reviewable here, in one list.
